# Beagclave Compliance Report
**Generated**: ${TIMESTAMP}
**Enclave**: ${ENCLAVE_NAME}
**Environment**: ${ENVIRONMENT}
**Resource Group**: ${RESOURCE_GROUP}

---

## Executive Summary

This report provides evidence of NIST SP 800-171, CMMC Level 2, ITAR, and EAR compliance
for the Beagclave enclave. All data is sourced from Microsoft Sentinel, Azure Policy, and
resource configurations.

